#!/usr/bin/env node
// Writes the public review test cases as one TypeScript module, so the site's Worker can run a new review
// precedent against them (apps/site/src/review-precedent-tests.ts). The private cases never go in.
//   node scripts/review-set/bundle-public.mjs          writes apps/site/src/generated/review-set-public-cases.generated.ts
// test/node/review-set.test.ts checks the written file is current.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "../..");
export const GENERATED_PATH = join(ROOT, "apps/site/src/generated/review-set-public-cases.generated.ts");

function textFilesUnder(directory) {
  const files = [];
  const walk = (folder) => {
    for (const entry of readdirSync(folder, { withFileTypes: true }).sort((first, second) => (first.name < second.name ? -1 : 1))) {
      const full = join(folder, entry.name);
      if (entry.isDirectory()) walk(full);
      else files.push({ path: relative(directory, full).split("\\").join("/"), text: readFileSync(full, "utf8") });
    }
  };
  walk(directory);
  return files;
}

/** The module's source, from review-set/cases. */
export function publicCasesSource(rootDirectory = ROOT) {
  const casesDirectory = join(rootDirectory, "review-set/cases");
  const cases = readdirSync(casesDirectory, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => ({ name: entry.name, ...JSON.parse(readFileSync(join(casesDirectory, entry.name, "case.json"), "utf8")), files: textFilesUnder(join(casesDirectory, entry.name, "game")) }));
  return [
    "// Generated by scripts/review-set/bundle-public.mjs from review-set/cases/. Don't edit: run the script.",
    'import type { ContentRule } from "@zaisma/core";',
    "",
    "export interface PublicReviewCase {",
    "  name: string;",
    "  title: string;",
    "  description: string;",
    "  is_honest: boolean;",
    "  content_rule: ContentRule | null;",
    "  protection: string | null;",
    "  why: string;",
    "  files: { path: string; text: string }[];",
    "}",
    "",
    `export const PUBLIC_REVIEW_CASES: PublicReviewCase[] = ${JSON.stringify(cases, null, 1)} as PublicReviewCase[];`,
    "",
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(GENERATED_PATH, publicCasesSource());
  console.log(`Wrote ${relative(ROOT, GENERATED_PATH)}`);
}
