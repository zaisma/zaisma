#!/usr/bin/env node
// Writes the components' script minified, as a TypeScript module the site serves in place of the readable one
// (apps/site/src/components/index.ts), so pages download 68 KB instead of 121 KB (22 KB instead of 34 KB gzipped).
//   node scripts/minify-components.mjs     writes apps/site/src/generated/components-script.generated.ts
// Run it (npm run components:minify) after changing any component's script. A script that wasn't minified from the
// source as it stands is served readable, never stale; test/node/components-script.test.ts checks the written file is current.

import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { transform } from "esbuild";
import { ROOT, loadComponentsModule } from "./components-module.mjs";

export const GENERATED_PATH = join(ROOT, "apps/site/src/generated/components-script.generated.ts");

/** The module's source for a script's readable text. */
export async function minifiedModuleSource(componentScriptSource) {
  const { code } = await transform(componentScriptSource, { minify: true, target: "es2020", legalComments: "none" });
  const sourceSha256 = createHash("sha256").update(componentScriptSource).digest("hex");
  return [
    "// Generated by scripts/minify-components.mjs from the components' scripts. Don't edit: run npm run components:minify.",
    `export const MINIFIED_COMPONENT_SCRIPT = { sourceSha256: ${JSON.stringify(sourceSha256)}, minifiedText: ${JSON.stringify(code)} };`,
    "",
  ].join("\n");
}

/** The components' readable script, as the site builds it. */
export async function readComponentScriptSource() {
  return (await loadComponentsModule()).COMPONENT_SCRIPT_SOURCE;
}

if (process.argv[1] === import.meta.filename) {
  writeFileSync(GENERATED_PATH, await minifiedModuleSource(await readComponentScriptSource()));
  console.log(`Wrote ${GENERATED_PATH}`);
}
