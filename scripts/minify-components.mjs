#!/usr/bin/env node
// Writes the components' script minified, as a TypeScript module the site serves in place of the readable one
// (apps/site/src/components/index.ts), so pages carry and download about half as much.
//   node scripts/minify-components.mjs     writes apps/site/src/generated/components-script.generated.ts
// Run it (npm run components:minify) after changing any component's script. A script that wasn't minified from the
// source as it stands is served readable, never stale; test/node/components-script.test.ts checks the written file is current.

import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { transform } from "esbuild";
import { ROOT, loadComponentsModule } from "./components-module.mjs";

export const GENERATED_PATH = join(ROOT, "apps/site/src/generated/components-script.generated.ts");

/** One script minified, as the generated module's line for it. */
async function minifiedLine(name, source) {
  const { code } = await transform(source, { minify: true, target: "es2020", legalComments: "none" });
  const sourceSha256 = createHash("sha256").update(source).digest("hex");
  return `export const ${name} = { sourceSha256: ${JSON.stringify(sourceSha256)}, minifiedText: ${JSON.stringify(code)} };`;
}

/** The first-paint script's pieces minified, each as a page carries it, by name. */
async function minifiedPiecesLine(pieces) {
  const entries = [];
  for (const piece of pieces) {
    const { code } = await transform(piece.source, { minify: true, target: "es2020", legalComments: "none" });
    entries.push(`  ${JSON.stringify(piece.name)}: { sourceSha256: ${JSON.stringify(createHash("sha256").update(piece.source).digest("hex"))}, minifiedText: ${JSON.stringify(code)} },`);
  }
  return `export const MINIFIED_FIRST_PAINT_PIECES = {\n${entries.join("\n")}\n};`;
}

/** The module's source for the scripts' readable texts: the first-paint script and its pieces, the look that follows it and the rest (components/index.ts). */
export async function minifiedModuleSource(firstPaintPieces, firstPaintScriptSource, lookScriptSource, componentScriptSource) {
  return [
    "// Generated by scripts/minify-components.mjs from the components' scripts. Don't edit: run npm run components:minify.",
    await minifiedPiecesLine(firstPaintPieces),
    await minifiedLine("MINIFIED_FIRST_PAINT_SCRIPT", firstPaintScriptSource),
    await minifiedLine("MINIFIED_LOOK_SCRIPT", lookScriptSource),
    await minifiedLine("MINIFIED_COMPONENT_SCRIPT", componentScriptSource),
    "",
  ].join("\n");
}

if (process.argv[1] === import.meta.filename) {
  const components = await loadComponentsModule();
  writeFileSync(GENERATED_PATH, await minifiedModuleSource(components.FIRST_PAINT_PIECES, components.FIRST_PAINT_SCRIPT_SOURCE, components.LOOK_SCRIPT_SOURCE, components.COMPONENT_SCRIPT_SOURCE));
  console.log(`Wrote ${GENERATED_PATH}`);
}
